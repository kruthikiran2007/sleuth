"""YARA rule auto-generator: turn a suspicious file into a hunting rule.

Analyst workflow this serves: you found something nasty and want to find
its siblings across your network. Instead of hand-writing a YARA rule,
Sleuth picks the file's most *distinctive* strings and emits a valid rule.

How "distinctive" is decided (rarity heuristic):
- longer strings score higher (short strings match everything),
- high Shannon entropy scores higher (random-looking tokens like mutex
  names, C2 paths, PDB leftovers are more unique than plain words),
- strings made only of common lowercase words are penalized (they are
  probably library boilerplate).

The generated rule is *self-tested*: it is compiled with yara-python and
matched against the source file before being written. If it does not
compile or does not match its own source, no file is written and the
failure is reported honestly — Sleuth never hands you a broken rule.

Graceful when yara-python is missing: a clear message, no crash.
"""

import hashlib
import os
import re

try:
    import yara
    _YARA_AVAILABLE = True
except ImportError:
    yara = None
    _YARA_AVAILABLE = False

from .strings import extract_strings, shannon_entropy

# Strings shorter than this are too generic to be rule-worthy.
_MIN_LEN = 8
# Cap: a rule with hundreds of strings is unwieldy; keep the best few.
_MAX_STRINGS = 12
# 200 MB cap mirrors detect.MAX_FILE_SIZE without importing detect.
_SIZE_LIMIT = 200 * 1024 * 1024

# Common English-ish tokens: strings built only from these are probably
# boilerplate (library banners, help text), not distinctive.
_COMMON_WORDS = {
    "the", "and", "for", "with", "this", "that", "from", "have", "error",
    "failed", "success", "warning", "info", "debug", "version", "copyright",
    "license", "http", "www", "com", "org", "net", "null", "true", "false",
    "string", "file", "data", "code", "test", "main", "init", "exit",
}


def _distinctiveness(s):
    """Score how unique *s* is likely to be across unrelated binaries."""
    entropy = shannon_entropy(s.encode("ascii", errors="ignore"))
    score = len(s) * (0.5 + entropy / 8.0)
    words = set(re.findall(r"[a-z]{3,}", s.lower()))
    if words and words <= _COMMON_WORDS:
        score *= 0.3  # pure boilerplate — penalize hard
    if re.search(r"[A-Z]{2,}|[0-9]{3,}|[_\\/.]{2,}", s):
        score *= 1.3  # mixed case / digits / path separators look unique
    return score


def _yara_escape(s):
    """Escape a string for a YARA double-quoted string literal."""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace(
        "\n", " ").replace("\r", " ")


def pick_distinctive_strings(strings, top_n=_MAX_STRINGS):
    """Return the *top_n* most distinctive strings from *strings*.

    Filters: min length, printable ASCII only, no NULs, deduplicated.
    Sorted by distinctiveness, best first.
    """
    seen = set()
    scored = []
    for s in strings or []:
        if len(s) < _MIN_LEN or s in seen:
            continue
        seen.add(s)
        if not re.fullmatch(r"[\x20-\x7e]+", s):
            continue
        scored.append((_distinctiveness(s), s))
    scored.sort(key=lambda item: -item[0])
    return [s for _, s in scored[:top_n]]


def build_rule_text(chosen, sha8):
    """Render the YARA rule source for *chosen* strings."""
    lines = [
        "rule sleuth_gen_%s {" % sha8,
        '    meta:',
        '        description = "Auto-generated by Sleuth - hunt siblings of a suspicious sample"',
        '        author = "sleuth"',
        "    strings:",
    ]
    for i, s in enumerate(chosen):
        lines.append('        $s%d = "%s"' % (i, _yara_escape(s)))
    need = min(5, max(1, len(chosen) // 2))
    lines.append("    condition:")
    lines.append("        %d of them" % need)
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate_rule(path, output_path=None):
    """Generate a YARA rule from the distinctive strings of *path*.

    Returns {"ok": bool, "rule_text": str|None, "written_to": str|None,
             "reason": str, "string_count": int}.

    The rule is compiled and matched against the source file first
    (self-test). On any failure — no distinctive strings, compile error,
    or the rule not matching its own source — ok is False, nothing is
    written, and *reason* says why, honestly.
    """
    if not _YARA_AVAILABLE:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "yara-python is not installed "
                          "(pip install yara-python)",
                "string_count": 0}
    if not os.path.isfile(path):
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "no such file: %s" % path, "string_count": 0}
    try:
        if os.path.getsize(path) > _SIZE_LIMIT:
            return {"ok": False, "rule_text": None, "written_to": None,
                    "reason": "file over size limit", "string_count": 0}
        with open(path, "rb") as f:
            data = f.read()
    except OSError as exc:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "cannot read file: %s" % exc, "string_count": 0}

    sha8 = hashlib.sha256(data).hexdigest()[:8]
    strings = extract_strings(data)
    chosen = pick_distinctive_strings(strings)
    if len(chosen) < 3:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "too few distinctive strings (%d found, need 3) "
                          "— this file has no rule-worthy content"
                          % len(chosen),
                "string_count": len(chosen)}

    rule_text = build_rule_text(chosen, sha8)

    # Self-test: compile, then prove it matches its own source.
    try:
        rules = yara.compile(source=rule_text)
    except Exception as exc:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "generated rule failed to compile: %s" % exc,
                "string_count": len(chosen)}
    try:
        matches = rules.match(data=data)
    except Exception as exc:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "self-test match failed: %s" % exc,
                "string_count": len(chosen)}
    if not matches:
        return {"ok": False, "rule_text": None, "written_to": None,
                "reason": "self-test failed: rule does not match its own "
                          "source file — refusing to write a broken rule",
                "string_count": len(chosen)}

    written_to = None
    if output_path:
        try:
            with open(output_path, "w") as f:
                f.write(rule_text)
            written_to = output_path
        except OSError as exc:
            return {"ok": True, "rule_text": rule_text, "written_to": None,
                    "reason": "rule is valid and self-tested, but could not "
                              "write to %s: %s" % (output_path, exc),
                    "string_count": len(chosen)}

    return {"ok": True, "rule_text": rule_text, "written_to": written_to,
            "reason": "rule compiled and matched its source file "
                      "(%d strings)" % len(chosen),
            "string_count": len(chosen)}
